// STRICT CHARACTER-KEYED DICTIONARY (ZERO MISMATCH GUARANTEED)
export const ALPHABET_STRICT_DICTIONARY: Record<string, LetterItem> = {};

// Populate vowels
for (const item of EXPANDED_VOWELS_DATA) {
  ALPHABET_STRICT_DICTIONARY[item.char] = item;
}

// Populate consonants
for (const item of EXPANDED_CONSONANTS_DATA) {
  ALPHABET_STRICT_DICTIONARY[item.char] = item;
}

/**
 * Strict lookup by Bengali character
 * Ensures selecting 'গ' strictly retrieves 'গ' (গরু, গাছ, গান, গাধা, গাজর...)
 * and NEVER 'ণ' (হরিণ, বীণা)!
 */
export const getLetterByCharStrict = (char: string): LetterItem => {
  if (ALPHABET_STRICT_DICTIONARY[char]) {
    return ALPHABET_STRICT_DICTIONARY[char];
  }
  // Fallback to searching
  const found = [...EXPANDED_VOWELS_DATA, ...EXPANDED_CONSONANTS_DATA].find((l) => l.char === char);
  if (found) return found;
  return EXPANDED_CONSONANTS_DATA[0]; // fallback to ক
};
