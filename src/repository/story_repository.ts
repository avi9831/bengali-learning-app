let fullStoriesCache: StoryItem[] | null = null;
let loadPromise: Promise<StoryItem[]> | null = null;

/**
 * Lazy Dynamic Loader for full story database (550KB JSON)
 */
export async function loadFullStories(): Promise<StoryItem[]> {
  if (fullStoriesCache) return fullStoriesCache;
  if (!loadPromise) {
    loadPromise = import('./story_db.json')
      .then((mod) => {
        const stories = ((mod.default || mod) as any).stories || [];
        fullStoriesCache = stories;
        // Merge into MORAL_STORIES references
        for (let i = 0; i < stories.length && i < MORAL_STORIES.length; i++) {
          MORAL_STORIES[i].wordsDict = stories[i].wordsDict;
        }
        return stories;
      })
      .catch((err) => {
        console.warn('Failed to load story_db.json:', err);
        return MORAL_STORIES;
      });
  }
  return loadPromise;
}

// Helper to look up breakdown of any word from stories or paragraphs
export function findStoryWordBreakdown(word: string): StoryWordData {
  const clean = word.replace(/[।,!?]/g, '').trim();

  // Search stories
  for (const story of MORAL_STORIES) {
    if (story.wordsDict && story.wordsDict[clean]) {
      return story.wordsDict[clean];
    }
  }

  // Search paragraphs
  for (const p of PARAGRAPH_COLLECTION) {
    if (p.wordsDict && p.wordsDict[clean]) {
      return p.wordsDict[clean];
    }
  }

  // Trigger lazy load if wordsDict not populated
  if (!fullStoriesCache) {
    loadFullStories();
  }

  // Fallback: Automatic grapheme breakdown
  const parts = clean.split('');
  return {
    word: clean,
    parts,
    partsAudio: parts,
    fullAudio: clean,
    meaning: 'প্রমিত বাংলা শব্দ',
    iconSymbol: '📖',
  };
}
