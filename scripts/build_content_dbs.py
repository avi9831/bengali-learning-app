def get_word_meaning(word: str) -> str:
    clean = re.sub(r'[।,!?\'"“”\-]', '', word).strip()
    if clean in word_to_meaning:
        return word_to_meaning[clean]
    if clean in COMMON_MEANINGS:
        return COMMON_MEANINGS[clean]
    # Check prefix/suffix stems
    for stem in [clean[:-1], clean[:-2], clean[1:]]:
        if stem in word_to_meaning:
            return word_to_meaning[stem]
        if stem in COMMON_MEANINGS:
            return COMMON_MEANINGS[stem]
    return f"১ {clean} - প্রমিত বাংলা ভাষার অর্থপূর্ণ ব্যাকরণসম্মত শব্দ।"

def make_sentence_entry(sid: str, text: str, icon: str, level: int) -> dict:
    raw_words = text.replace('।', '').replace(',', '').replace('!', '').replace('?', '').split()
    words_dict = {}
    for w in raw_words:
        clean = re.sub(r'[।,!?\'"“”\-]', '', w).strip()
        words_dict[clean] = {
            "word": clean,
            "breakdown": breakdown_word(clean),
            "partsAudio": breakdown_word(clean),
            "meaning": get_word_meaning(clean),
            "ttsAudio": clean,
            "icon": icon
        }
    return {
        "id": sid,
        "level": level,
        "sentence": text,
        "words": raw_words,
        "icon": icon,
        "ttsAudio": text,
        "wordsDict": words_dict
    }

