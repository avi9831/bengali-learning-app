def repair_bengali_text(text: str) -> str:
    """
    Crucial Bengali Complex Text Layout (CTL) Repair Function:
    Fixes visual-to-logical character swapping and decomposed glyphs from PDF extraction:
    1. Recombines adjacent decomposed O-kar (\u09C7\u09BE -> \u09CB) and Ou-kar (\u09C7\u09D7 / \u09C7\u09CC -> \u09CC).
    2. Reconstructs split O-kar (ে + Consonant + া -> Consonant + ো) and Ou-kar (ে + Consonant + ৗ/ৌ -> Consonant + ৌ)
       around single consonants or conjunct clusters (e.g., 'েঘা' -> 'ঘো', 'েখাঁ' -> 'খোঁ', 'েখৗ' -> 'খৌ').
    3. Swaps left-sided vowel signs: if an E-kar (ে: \u09C7), Oi-kar (ৈ: \u09C8), or I-kar (ি: \u09BF)
       appears BEFORE a consonant without a preceding consonant, swaps them using regex so the consonant comes first:
       - 'ে' + 'ঘ' -> 'ঘ' + 'ে' ('ঘে')
       - 'ি' + 'ঘ' -> 'ঘ' + 'ি' ('ঘি')
       - 'ৈ' + 'ঘ' -> 'ঘ' + 'ৈ' ('ঘৈ')
       - 'ে' + 'খ' -> 'খ' + 'ে' ('খে')
    4. Normalizes to standard Unicode NFC form.
    """
    if not text:
        return ""

    text = unicodedata.normalize('NFC', text)

    # 1. Adjacent decomposed vowels
    text = text.replace('\u09C7\u09BE', '\u09CB')
    text = text.replace('\u09C7\u09D7', '\u09CC').replace('\u09C7\u09CC', '\u09CC')
    text = text.replace('\u09C7\u0981\u09BE', '\u09CB\u0981').replace('\u0981\u09C7\u09BE', '\u0981\u09CB')

    # Consonant unit pattern: single consonant with nukta or conjunct with hasanta
    c_unit = r'(?:[\u0995-\u09B9\u09DC-\u09DF]\u09BC?\u09CD)*[\u0995-\u09B9\u09DC-\u09DF]\u09BC?'
    cons_char = r'[\u0995-\u09B9\u09DC-\u09DF]'

    # 2. Reconstruct split O-kar around consonant: (ে + Consonant + া -> Consonant + ো)
    text = re.sub(
        rf'(?<!{cons_char})\u09C7({c_unit})(\u0981?)\u09BE',
        lambda m: m.group(1) + '\u09CB' + m.group(2),
        text
    )

    # 3. Reconstruct split Ou-kar around consonant: (ে + Consonant + ৗ/ৌ -> Consonant + ৌ)
    text = re.sub(
        rf'(?<!{cons_char})\u09C7({c_unit})(\u0981?)[\u09D7\u09CC]',
        lambda m: m.group(1) + '\u09CC' + m.group(2),
        text
    )

    # 4. Swap left-sided vowel signs: E-kar (ে), Oi-kar (ৈ), I-kar (ি) before a consonant
    pattern = rf'(?<!{cons_char})([\u09C7\u09C8\u09BF])({c_unit})'
    for _ in range(5):
        if not re.search(pattern, text):
            break
        text = re.sub(pattern, lambda m: m.group(2) + m.group(1), text)

    return unicodedata.normalize('NFC', text)


def normalize_bengali_unicode(text: str) -> str:
    """
    Standard Bengali Unicode Normalizer using repair_bengali_text.
    """
    return repair_bengali_text(text)


def clean_headword(raw_word: str) -> str:
    """
    Aggressive Headword Cleaning:
    - Strips ALL superscripts (¹, ², ³, etc.) and subscripts
    - Strips numbers (ASCII 0-9 and Bengali ০-৯)
    - Strips zero-width joiners / non-joiners (ZWNJ \u200C, ZWJ \u200D, \u200B, \uFEFF)
    - Strips part-of-speech tags and annotations (e.g., [বি.], (বিণ.), [সং.])
    - Strips brackets, parentheses, hyphens, punctuation, and whitespace
    - Normalizes Bengali Unicode and fixes decomposed O-kar / Ou-kar
    - Preserves only authentic Bengali letters, kar signs, and modifiers.
    e.g., 'খোকা¹' -> 'খোকা' (so startswith('খো') returns True)
    e.g., 'খোঁড়া¹' -> 'খোঁড়া'
    e.g., '[খোদা]' -> 'খোদা'
    e.g., 'খোদা (বি.)' -> 'খোদা'
    """
    if not raw_word:
        return ""

    # Step 1: Repair Bengali CTL / visual order and normalize Unicode
    text = repair_bengali_text(raw_word)

    # Step 2: Strip grammatical/part-of-speech annotations e.g. [বি.], (বিণ.), [সং.]
    text = re.sub(
        r'[\(\[\{⟨【〔<]\s*(?:বি|বিণ|ক্রি|ক্রিবি|অব্য|সর্ব|সং|ফার|আর|তৎ|দেশি|উ|প্রা|ব|স্ত্রী|পুং|নপুং)[^\)\]\}⟩】〕>]*[\)\]\}⟩】〕>]',
        '',
        text
    )

    # Step 3: Strip standalone brackets, parentheses, braces, angle brackets
    text = re.sub(r'[()\[\]{}⟨⟩【】〔〕<>]', '', text)

    # Step 4: Strip zero-width characters (ZWNJ, ZWJ, BOM)
    text = re.sub(r'[\u200B-\u200D\uFEFF]', '', text)

    # Step 5: Strip superscripts and subscripts (e.g. খোকা¹ -> খোকা)
    text = re.sub(r'[¹²³⁴⁵⁶⁷⁸⁹⁰₀₁₂₃₄₅₆₇₈₉\u00B9\u00B2\u00B3\u2070-\u207F\u2080-\u208F]', '', text)

    # Step 6: Strip numbers (ASCII 0-9 and Bengali digits ০-৯)
    text = re.sub(r'[0-9\u09E6-\u09EF]', '', text)

    # Step 7: Strip punctuation, symbols, hyphens, and whitespace
    text = re.sub(r'[।॥,;:!?.\'\"“”‘’`_+=\/\\|*~^§#@$%&–—\-\s]', '', text)

    # Step 8: Keep only valid Bengali Unicode characters (\u0980-\u09FF)
    text = re.sub(r'[^\u0980-\u09FF]', '', text)

    # Step 9: Final NFC normalization
    return unicodedata.normalize('NFC', text.strip())


def word_matches_consonant_kar(word: str, consonant: str, kar_sign: str) -> bool:
    """
    Robust Category Matching (Starts-With Logic):
    Verifies if word begins with the target Consonant + Kar combination.
    Strips all Chandrabindu (ঁ) and Japhala (্য) when matching against the base
    query, but the original word is preserved in the final output.
    e.g., for 'ঘ' + 'ে' ('ঘে'): matches 'ঘেউ', 'ঘেঁটু', 'ঘেরা', 'ঘেরাটোপ'
    e.g., for 'খ' + 'ৃ' ('খৃ'): matches 'খ্রিস্ট', 'খ্রিস্টান', 'খৃষ্ট'
    e.g., for 'খ' + 'ৌ' ('খৌ'): matches 'খৌদ', 'খৌরাক', 'খৌল'
    e.g., for 'খ' + 'ো' ('খো'): matches 'খোঁড়া', 'খোঁপা', 'খোকন', 'খোকা', 'খোদা'
    """
    w_norm = unicodedata.normalize('NFC', word)
    c_norm = unicodedata.normalize('NFC', consonant)
    k_norm = unicodedata.normalize('NFC', kar_sign)
    target = f"{c_norm}{k_norm}"

    # Strip all Chandrabindu (ঁ: \u0981) and Japhala (্য: \u09CD\u09AF) for comparison
    stripped = w_norm.replace('\u0981', '').replace('\u09CD\u09AF', '')
    stripped = unicodedata.normalize('NFC', stripped)

    if stripped.startswith(target):
        return True

    # Also regex with optional nukta, chandrabindu, japhala before and after kar sign
    reg = re.compile(rf'^{re.escape(c_norm)}\u09BC?(?:\u0981|\u09CD\u09AF)?{re.escape(k_norm)}')
    return bool(reg.match(w_norm))


def build_kar_starts_with_regex(consonant: str, kar_sign: str) -> re.Pattern:
    """
    Constructs a regex for matching words starting with Consonant + Kar sign.
    """
    c = unicodedata.normalize('NFC', consonant)
    k = unicodedata.normalize('NFC', kar_sign)
    pattern = rf'^{re.escape(c)}\u09BC?(?:\u0981|\u09CD\u09AF)?{re.escape(k)}[\u0980-\u09FF]*$'
    return re.compile(pattern)


def breakdown_bengali_word(word: str) -> List[str]:
    """
    Deconstructs a Bengali word into individual grapheme / phonetic components:
    Independent vowels, consonants, hasanta, kar signs, and modifiers.
    e.g. 'অকথা' -> ['অ', 'ক', 'থ', 'া']
    e.g. 'আকাশ' -> ['আ', 'ক', 'া', 'শ']
    e.g. 'খোকা' -> ['খ', 'ো', 'ক', 'া']
    """
    if not word:
        return []
    normalized = normalize_bengali_unicode(word.strip().replace('।', '').replace(',', ''))
    chars = []
    for ch in normalized:
        if '\u0980' <= ch <= '\u09FF':
            chars.append(ch)
        elif ch.strip():
            chars.append(ch)
    return chars if chars else list(word)


