        'লতা', 'বার', 'দার', 'খানা', 'পুর', 'নগর', 'বাসী', 'শীল', 'বান',
        'হীন', 'ময়', 'সভা', 'সংঘ', 'দল', 'রূপ', 'বিদ্যা', 'কক্ষ', 'ঘর',
        'বন', 'জল', 'ঘাট', 'পথ', 'দ্বার', 'দেশ', 'মাঠ', 'পর্ব', 'কাল',
        'বেলা', 'দিন', 'রাত', 'লোক', 'কুল', 'শালা', 'শাখা', 'ফুল', 'ফল',
