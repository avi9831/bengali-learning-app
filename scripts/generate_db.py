# 3. PDF Dictionary Parser & Authentic Kar Vocabulary
# ---------------------------------------------------------------------------
def extract_dictionary_pdf_words(pdf_path: Optional[str] = None) -> List[Dict[str, str]]:
    """
    Overhauled PDF Dictionary Parser for Bangla Academy Samkshipta Bangla Abhidhan.
    Extracts headwords (ভুক্তিশব্দ) and authentic meanings directly from the PDF:
    1. Column-by-Column Reading:
       Reads left column entirely first, then right column. Never reads straight across.
       Uses PyMuPDF (fitz) or pdfplumber with fallback.
    2. Bengali Text Repair:
       Applies repair_bengali_text to resolve CTL visual vowel reversals and split O-kar / Ou-kar.
    3. Headword Regex Extraction:
       Captures headwords using regex matching line start followed by POS tag or numbers:
       ^([\u0980-\u09FF]+)(?:¹|²|³|০|১|২|৩|৪|৫|৬|৭|৮|৯)*\s*(?:বি|বিণ|ক্রি|অব্য)
    """
    candidates = [
        pdf_path,
        "Bangla Academy Samkshipta Bangla Abhidhan (2008).pdf",
        "./Bangla Academy Samkshipta Bangla Abhidhan (2008).pdf",
        "/Bangla Academy Samkshipta Bangla Abhidhan (2008).pdf",
        "assets/Bangla Academy Samkshipta Bangla Abhidhan (2008).pdf"
    ]
    found_path = None
    for p in candidates:
        if p and os.path.exists(p):
            found_path = p
            break

    if not found_path:
        for root_dir, _, files in os.walk("."):
            for f in files:
                if f.lower().endswith(".pdf") and ("bangla" in f.lower() or "abhidhan" in f.lower() or "dictionary" in f.lower()):
                    found_path = os.path.join(root_dir, f)
                    break
            if found_path:
                break

    if not found_path:
        return []

    print(f"[*] Extracting headwords column-by-column from PDF: {found_path}")
    extracted: List[Dict[str, str]] = []
    seen_hw = set()

    # Regex specified in Requirement 3:
    headword_regex = re.compile(
        r'^([\u0980-\u09FF]+)(?:¹|²|³|০|১|২|৩|৪|৫|৬|৭|৮|৯|[0-9])*\s*(?:বি|বিণ|ক্রি|অব্য|[০-৯১-৯]|\(|\[)\s*[:\-–—]?\s*(.*)$'
    )

    column_texts: List[str] = []

    # 1. Try PyMuPDF (fitz) for precise column-by-column bounding box extraction
    try:
        import fitz
        doc = fitz.open(found_path)
        print(f"[*] PyMuPDF (fitz) opened: {len(doc)} pages")
        for page in doc:
            w = page.rect.width
            h = page.rect.height
            mid_x = w / 2.0
            # Left column rect
            left_rect = fitz.Rect(0, 0, mid_x, h)
            # Right column rect
            right_rect = fitz.Rect(mid_x, 0, w, h)

            left_txt = page.get_text("text", clip=left_rect) or ""
            right_txt = page.get_text("text", clip=right_rect) or ""

            if left_txt.strip():
                column_texts.append(left_txt)
            if right_txt.strip():
                column_texts.append(right_txt)
    except ImportError:
        pass
    except Exception as e:
        print(f"[!] PyMuPDF extraction note: {e}")

    # 2. Try pdfplumber if PyMuPDF was not available
    if not column_texts:
        try:
            import pdfplumber
            print("[*] Trying pdfplumber column extraction")
            with pdfplumber.open(found_path) as pdf:
                for page in pdf.pages:
                    w, h = page.width, page.height
                    mid_x = w / 2.0
                    left_crop = page.crop((0, 0, mid_x, h))
                    right_crop = page.crop((mid_x, 0, w, h))

                    left_txt = left_crop.extract_text() or ""
                    right_txt = right_crop.extract_text() or ""

                    if left_txt.strip():
                        column_texts.append(left_txt)
                    if right_txt.strip():
                        column_texts.append(right_txt)
        except ImportError:
            pass
        except Exception as e:
            print(f"[!] pdfplumber extraction note: {e}")

    # 3. Fallback to pypdf
    if not column_texts:
        try:
            import pypdf
            reader = pypdf.PdfReader(found_path)
            print(f"[*] pypdf fallback: {len(reader.pages)} pages")
            for page in reader.pages:
                txt = page.extract_text()
                if txt and txt.strip():
                    column_texts.append(txt)
        except Exception as e:
            print(f"[!] pypdf extraction note: {e}")

    # Process all column texts with Bengali Text Repair and Headword Regex Extraction
    for col_txt in column_texts:
        # Step 2: Repair Bengali CTL / visual reversals and split vowels
        repaired_txt = repair_bengali_text(col_txt)

        for line in repaired_txt.splitlines():
            line = line.strip()
            if not line:
                continue

            # Step 3: Match headword line
            m = headword_regex.match(line)
            if m:
                raw_hw = m.group(1).strip()
                raw_def = m.group(2).strip() if m.lastindex >= 2 else ""

                # Support comma-separated headwords on same line e.g. "ঘেঁটু, ঘেটু"
                sub_words = raw_hw.split(',')
                for sw in sub_words:
                    hw = clean_headword(sw)
                    if len(hw) >= 1 and hw not in seen_hw:
                        seen_hw.add(hw)
                        meaning = re.sub(r'\s+', ' ', raw_def).strip() or f"১ {hw} শব্দের প্রমিত অর্থ।"
                        extracted.append({"w": hw, "m": meaning[:250]})
            else:
                # Secondary scanner for lines with part-of-speech or colon
                sub_m = re.match(r'^([\u0980-\u09FF]+)\s+[:\-–—]\s*(.+)$', line)
                if sub_m:
                    hw = clean_headword(sub_m.group(1))
                    if len(hw) >= 1 and hw not in seen_hw:
                        seen_hw.add(hw)
                        extracted.append({"w": hw, "m": sub_m.group(2).strip()[:250]})

    print(f"[*] Extracted {len(extracted)} cleaned headwords from PDF.")
    return extracted


